#!/usr/bin/env python3
"""
collect_news.py — Semi-automated Deep Learning weekly news collector.

Aggregates headlines from RSS feeds and free APIs into a weekly summary
Markdown file. Run with:

    python collect_news.py --output archives/2026-W47.md

Requires: pip install feedparser requests python-dateutil
"""

import argparse
import time
import datetime
import json
import sys
from pathlib import Path

try:
    import feedparser
except ImportError:
    print("feedparser not installed. Run: pip install feedparser")
    sys.exit(1)

# ── RSS Feeds to monitor ──────────────────────────────────────────────
FEEDS = [
    {
        "name": "arXiv cs.LG (Deep Learning)",
        "url": "http://export.arxiv.org/rss/cs.LG",
        "category": "Research Papers",
    },
    {
        "name": "arXiv cs.AI (Artificial Intelligence)",
        "url": "http://export.arxiv.org/rss/cs.AI",
        "category": "Research Papers",
    },
    {
        "name": "Hacker News (via RSS)",
        "url": "https://hnrss.org/frontpage",
        "category": "Community",
    },
    {
        "name": "The Gradient",
        "url": "https://thegradient.pub/rss/",
        "category": "Curated Analysis",
    },
    {
        "name": "Lilian Weng's Blog",
        "url": "https://lilianweng.github.io/index.xml",
        "category": "Curated Analysis",
    },
    {
        "name": "Jay Alammar's Blog",
        "url": "https://jalammar.github.io/feed/",
        "category": "Tutorials",
    },
]


def fetch_feed(feed: dict, days: int = 7) -> list[dict]:
    """Fetch and filter entries from an RSS feed to the last N days."""
    entries = []
    try:
        d = feedparser.parse(feed["url"])
        cutoff = datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(days=days)
        for entry in d.entries:
            published = getattr(entry, "published_parsed", None)
            if published:
                pub_date = datetime.datetime.fromtimestamp(
                    time.mktime(published), tz=datetime.timezone.utc
                )
                if pub_date >= cutoff:
                    entries.append({
                        "title": entry.get("title", "Untitled"),
                        "link": entry.get("link", ""),
                        "summary": entry.get("summary", "")[:200],
                        "source": feed["name"],
                        "category": feed["category"],
                        "published": pub_date.strftime("%Y-%m-%d"),
                    })
    except Exception as e:
        print(f"  ! Failed to fetch {feed['name']}: {e}")
    return entries


def group_by_category(entries: list[dict]) -> dict[str, list[dict]]:
    """Group entries by their category."""
    groups = {}
    for entry in entries:
        cat = entry["category"]
        groups.setdefault(cat, []).append(entry)
    return groups


def generate_markdown(groups: dict[str, list[dict]], week_label: str) -> str:
    """Generate a Markdown summary from grouped entries."""
    lines = [
        f"# Deep Learning Weekly — {week_label}",
        "",
        f"> Auto-collected on {datetime.date.today().isoformat()}.",
        "> Review and edit each section before publishing.",
        "",
    ]

    for category, entries in sorted(groups.items()):
        lines.append(f"## {category}")
        lines.append("")
        for e in entries[:15]:  # Limit to 15 per category
            lines.append(f"- **[{e['title']}]({e['link']})** — {e['source']} ({e['published']})")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by `collect_news.py`. Edit and curate before publishing.*")
    return "\n".join(lines)


def main():

    parser = argparse.ArgumentParser(description="Collect deep learning news")
    parser.add_argument(
        "--output", "-o",
        type=str,
        required=True,
        help="Output Markdown file path (e.g., archives/2026-W47.md)",
    )
    parser.add_argument(
        "--days", "-d",
        type=int,
        default=7,
        help="Number of days to look back (default: 7)",
    )
    parser.add_argument(
        "--max-per-feed", "-m",
        type=int,
        default=20,
        help="Max entries per feed (default: 20)",
    )
    args = parser.parse_args()

    print(f"Fetching feeds for the last {args.days} days...")
    all_entries = []
    for feed in FEEDS:
        print(f"  > {feed['name']}")
        entries = fetch_feed(feed, days=args.days)
        all_entries.extend(entries[:args.max_per_feed])

    groups = group_by_category(all_entries)
    week_label = (
        f"Week of {datetime.date.today().strftime('%B %d, %Y')}"
    )
    md = generate_markdown(groups, week_label)

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(md, encoding="utf-8")
    print(f"\n✅ Wrote {len(all_entries)} entries to {output_path}")


if __name__ == "__main__":
    main()
